// Longer Persian texts. `bot` is the bot's username without @ (examples use it).
import { esc } from './util.js';

const at = (bot) => (bot ? `@${esc(bot)}` : '@bot');

export function welcomeText(name, bot) {
  const b = at(bot);
  return `👋 سلام ${esc(name || 'دوست من')}!\n\n`
    + 'من ربات <b>نجوا</b> هستم 🤫 با من توی هر چتی پیامی می‌فرستی که <b>فقط گیرنده‌اش</b> می‌تونه بخونه.\n\n'
    + '✍️ <b>روش ارسال:</b> توی هر چتی (گروه یا پی‌وی) بنویس:\n'
    + `<code>${b} متن نجوا @username</code>\n`
    + 'یا با آیدی عددی گیرنده:\n'
    + `<code>${b} متن نجوا 123456789</code>\n`
    + 'و بعد روی نتیجه‌ی «🔒 نجوا برای ...» بزن.\n\n'
    + '🔹 <b>نمونه‌ها</b>\n'
    + `• <code>${b} فردا ساعت ۵ 😉 @ali</code>\n`
    + `• <code>${b} !رمز وای‌فای 1234 @sara</code> ← یک‌بار مصرف 🔥\n`
    + `• <code>${b} جلسه لغو شد @ali @reza 1h</code> ← چند گیرنده + انقضا ⏳\n\n`
    + 'راهنمای کامل: /help';
}

export function helpText(bot) {
  const b = at(bot);
  return '📖 <b>راهنمای کامل ربات نجوا</b>\n\n'
    + '1️⃣ <b>نجوای ساده</b>\n'
    + `<code>${b} متن @username</code> یا <code>${b} متن 123456789</code>\n`
    + 'گیرنده را می‌شود اول هم نوشت: <code>' + b + ' @username متن</code>\n'
    + 'فقط گیرنده و خودت متن را با دکمه‌ی «👁 نمایش نجوا» می‌بینید؛ بقیه پیام «این نجوا مال تو نیست 😏» می‌گیرند.\n\n'
    + '2️⃣ <b>چند گیرنده</b> — تا ۳ نفر:\n'
    + `<code>${b} متن @ali @sara 123456789</code>\n\n`
    + '3️⃣ <b>دیده شد</b> — وقتی گیرنده بازش کند، زیر پیام «👁 دیده شد» می‌آید.\n\n'
    + '4️⃣ <b>رسید خواندن</b> — اگر ربات را استارت کرده باشی، وقتی گیرنده بازش کند در پی‌وی خبرت می‌کنم (قابل خاموش کردن در ⚙️ تنظیمات).\n\n'
    + '5️⃣ <b>یک‌بار مصرف</b> — اول متن «!» بگذار: <code>' + b + ' !متن @ali</code>\n'
    + 'بعد از اولین بار دیدن، متن از ربات پاک می‌شود و پیام «🔥 نجوا سوزانده شد» می‌شود.\n\n'
    + '6️⃣ <b>زمان انقضا</b> — آخر پیام مدت بنویس: <code>30m</code> (دقیقه)، <code>1h</code> (ساعت)، <code>2d</code> (روز، حداکثر ۷ روز):\n'
    + `<code>${b} متن @ali 30m</code> — بعد از آن دیگر باز نمی‌شود. انقضای پیش‌فرض را هم در ⚙️ تنظیمات می‌شود گذاشت.\n\n`
    + '7️⃣ <b>فضول‌ها</b> — هر کس که گیرنده نیست و دکمه را بزند شمرده می‌شود («👀 ۲ فضول»). اسمشان را در 📜 تاریخچه ← جزئیات نجوا می‌بینی.\n\n'
    + '8️⃣ <b>نجوای طولانی</b> — متن بیشتر از ۲۰۰ کاراکتر در پنجره جا نمی‌شود؛ دکمه‌ی «📖 خواندن در ربات» متن کامل را فقط برای گیرنده و فرستنده در پی‌وی ربات نشان می‌دهد.\n\n'
    + '9️⃣ <b>تاریخچه</b> — /history: ۲۰ نجوای آخر ارسالی و دریافتی. در حالت اینلاین هم اگر فقط متن بنویسی، ۳ گیرنده‌ی اخیرت را برای ارسال سریع پیشنهاد می‌کنم.\n\n'
    + '🔟 <b>لیست بلاک و تنظیمات</b> — /blocks: هر کس را بلاک کنی دیگر نمی‌تواند برایت نجوا بسازد. /settings: رسید خواندن و انقضای پیش‌فرض.\n\n'
    + '🔒 متن نجوا هیچ‌وقت داخل خود پیام یا دکمه‌ها نیست و فقط در دیتابیس ربات می‌ماند؛ حتی مالک ربات هم آن را نمی‌بیند.';
}

export const MAIN_HINT = 'برای ارسال نجوا از حالت اینلاین استفاده کن: در هر چتی نام ربات را تایپ کن، بعد متن و گیرنده.';
