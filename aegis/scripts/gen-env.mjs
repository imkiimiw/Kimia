// Writes tgcloud/lib/env.js: the deploy-time configuration the modules read (the platform gives
// deployed code no environment variables). Only non-secret values belong here — never a token.
//   AEGIS_OWNER_ID  the Super Admin's numeric id (default 5557901897)
import fs from 'node:fs';
import path from 'node:path';
import { loadEnv, ROOT } from './dotenv.mjs';

const DEFAULT_OWNER = 5557901897;
const env = loadEnv();
const raw = env.AEGIS_OWNER_ID === undefined || env.AEGIS_OWNER_ID === '' ? String(DEFAULT_OWNER) : env.AEGIS_OWNER_ID;
if (!/^[1-9]\d{4,15}$/.test(raw)) {
  console.error(`AEGIS_OWNER_ID must be a positive numeric Telegram user id, got "${raw}"`);
  process.exit(1);
}
const file = path.join(ROOT, 'tgcloud/lib/env.js');
const src = `/*
 * Deploy-time configuration, generated by scripts/gen-env.mjs from aegis/.env (or the environment).
 * Edit .env and run \`npm run build\`, not this file. No secrets here: it is deployed as code.
 */
export const AEGIS_OWNER_ID = ${Number(raw)};
`;
const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
if (before !== src) fs.writeFileSync(file, src);
console.log(`✔ tgcloud/lib/env.js: AEGIS_OWNER_ID = ${raw}${Number(raw) === DEFAULT_OWNER ? ' (default)' : ''}`);
