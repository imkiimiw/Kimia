// The locale files: aegis/locales/<lang>/<namespace>.json, each a flat { key: "text" } object.
// A string's full key is "<namespace>.<key>". Strings are Telegram HTML (parse_mode HTML) and may
// use {placeholders}. Shared by scripts/build-locales.mjs and the unit tests.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './dotenv.mjs';

export const LANGS = ['fa', 'en', 'ru', 'zh', 'fr'];
export const LOCALES_DIR = path.join(ROOT, 'locales');
export const OUT_DIR = path.join(ROOT, 'tgcloud/lib/i18n/strings');

/** { lang: { "ns.key": "text" } } plus the problems found while reading. */
export function readLocales() {
  const dicts = {};
  const problems = [];
  for (const lang of LANGS) {
    const dir = path.join(LOCALES_DIR, lang);
    dicts[lang] = {};
    if (!fs.existsSync(dir)) {
      problems.push(`${lang}: folder locales/${lang}/ is missing`);
      continue;
    }
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
      const ns = file.replace(/\.json$/, '');
      let data;
      try {
        data = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
      } catch (e) {
        problems.push(`${lang}/${file}: invalid JSON (${e.message})`);
        continue;
      }
      for (const [k, v] of Object.entries(data)) {
        if (typeof v !== 'string') problems.push(`${lang}/${file}: "${k}" is not a string`);
        else dicts[lang][`${ns}.${k}`] = v;
      }
    }
  }
  return { dicts, problems };
}

const placeholders = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');

/** Every key in every language, the same placeholders everywhere, no empty strings. */
export function validate(dicts) {
  const problems = [];
  const all = new Set();
  for (const lang of LANGS) for (const k of Object.keys(dicts[lang] || {})) all.add(k);
  for (const key of [...all].sort()) {
    const ref = dicts.en[key];
    for (const lang of LANGS) {
      const v = (dicts[lang] || {})[key];
      if (v === undefined) {
        problems.push(`${lang}: missing key "${key}"`);
        continue;
      }
      if (!v.trim()) problems.push(`${lang}: empty string "${key}"`);
      if (ref !== undefined && placeholders(v) !== placeholders(ref)) {
        problems.push(`${lang}: "${key}" has placeholders {${placeholders(v)}} but en has {${placeholders(ref)}}`);
      }
    }
  }
  return problems;
}

/** The runtime module for one language (deterministic: keys sorted, one per line). */
export function render(lang, dict) {
  const lines = Object.keys(dict).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(dict[k])},`);
  return `/*\n * GENERATED by scripts/build-locales.mjs from aegis/locales/${lang}/*.json — do not edit here.\n */\nexport default {\n${lines.join('\n')}\n};\n`;
}
