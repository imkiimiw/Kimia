export type Lang = keyof typeof STUDIO_TEXTS;
export type Key = keyof (typeof STUDIO_TEXTS)['fa'];

const fa = (s: string) => s.replace(/\d/g, (d) => String.fromCharCode(0x06f0 + Number(d)));

/** A number in the language's digits. */
export const num = (lang: Lang, n: number | string) => (lang === 'fa' ? fa(String(n)) : String(n));

export function makeT(lang: Lang) {
  return (key: Key, vars: Record<string, string | number> = {}) =>
    (STUDIO_TEXTS[lang][key] as string).replace(/\{(\w+)\}/g, (_, k) => {
      const v = vars[k];
      if (v === undefined) return '';
      return lang === 'fa' && /^[\d.,×x ]+$/.test(String(v)) ? fa(String(v)).replace('.', '٫') : String(v);
    });
}
