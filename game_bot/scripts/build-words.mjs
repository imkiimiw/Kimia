// Builds tgcloud/lib/words/{en,fr,ru,fa}.js — the Codeword answer and guess lists — from:
//   freq_<lang>.txt   FrequencyWords 2018 50k lists (github.com/hermitdave/FrequencyWords, CC BY-SA 4.0)
//   dic_<lang>/package/index.dic   Hunspell dictionaries from npm: dictionary-en (MIT AND BSD),
//                                  dictionary-fr (MPL-2.0), dictionary-ru (BSD-3-Clause), dictionary-fa (Apache-2.0)
// Answers: the most frequent 5-letter words that are also dictionary entries (which keeps names and
// typos out). Guesses: every 5-letter dictionary entry plus frequent 5-letter words (inflections).
// Usage: node scripts/build-words.mjs <folder with the sources>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalize, wellFormed } from '../tgcloud/lib/games/codeword.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2];
if (!SRC) {
  console.error('usage: node scripts/build-words.mjs <sources folder>');
  process.exit(1);
}

const ANSWERS = { en: 1500, fr: 1000, ru: 1000, fa: 800 };
const MIN_COUNT = { en: 40, fr: 30, ru: 30, fa: 30 }; // frequent enough to accept as a guess
// Persian answers skip conjugated verbs (می‌/نمی‌ prefixes; subtitles are full of them).
const answerShape = { fa: (w) => !/^(می|نمی|بی)/.test(w) };
// Words never picked as answers (still accepted as guesses).
const BLOCK = {
  en: ['gonna', 'wanna', 'gotta', 'kinda', 'sorta', 'outta', 'lemme', 'gimme', 'dunno', 'yeahs', 'bitch', 'whore', 'pussy', 'dicks', 'cocks', 'boobs', 'horny', 'nigga', 'sexed', 'sluts', 'penis', 'semen', 'vagina', 'bitch', 'fucks', 'shits', 'crack', 'drunk', 'killa', 'nazis', 'rapes', 'raped'],
  fr: ['putes', 'salop', 'merde', 'conne', 'bites', 'pedes', 'nique', 'chier', 'couil'],
  ru: ['блядь', 'хуйня', 'пизда', 'ебать', 'сучка', 'шлюха', 'говно', 'мудак', 'ублюд'],
  fa: ['جنده', 'کونی', 'لاشی', 'کثافت', 'حرومی', 'شرلوک', 'مایکل', 'جیمز', 'دیوید', 'جورج', 'رابرت', 'چارلی', 'ریچارد'],
};
const SOURCES = 'FrequencyWords (Hermit Dave, CC BY-SA 4.0) and the Hunspell dictionaries dictionary-en (MIT AND BSD), dictionary-fr (MPL-2.0), dictionary-ru (BSD-3-Clause), dictionary-fa (Apache-2.0)';

function dictionary(lang) {
  const lines = fs.readFileSync(path.join(SRC, `dic_${lang}`, 'package', 'index.dic'), 'utf8').split('\n').slice(1);
  const out = new Set();
  for (const line of lines) {
    const word = line.split(/[/\t ]/)[0].trim();
    if (!word) continue;
    if (lang !== 'fa' && word[0] !== word[0].toLowerCase()) continue; // proper nouns are capitalized
    const n = normalize(lang, word);
    if (wellFormed(lang, n)) out.add(n);
  }
  return out;
}

function frequent(lang) {
  const out = [];
  for (const line of fs.readFileSync(path.join(SRC, `freq_${lang}.txt`), 'utf8').split('\n')) {
    const [word, n] = line.trim().split(' ');
    if (!word) continue;
    const w = normalize(lang, word);
    if (wellFormed(lang, w)) out.push([w, Number(n)]);
  }
  return out;
}

for (const lang of ['en', 'fr', 'ru', 'fa']) {
  const dic = dictionary(lang);
  const freq = frequent(lang);
  const block = new Set(BLOCK[lang].map((w) => normalize(lang, w)));
  const answers = [];
  const seen = new Set();
  for (const [w] of freq) {
    if (answers.length >= ANSWERS[lang]) break;
    if (seen.has(w) || !dic.has(w) || block.has(w) || (answerShape[lang] && !answerShape[lang](w))) continue;
    seen.add(w);
    answers.push(w);
  }
  // Persian Hunspell is huge and full of rare compounds: keep only its words that also occur in the corpus.
  const inCorpus = new Set(freq.map(([w]) => w));
  const allowed = new Set(lang === 'fa' ? Array.from(dic).filter((w) => inCorpus.has(w)) : dic);
  for (const [w, n] of freq) if (n >= MIN_COUNT[lang]) allowed.add(w);
  for (const w of answers) allowed.add(w);
  const extra = Array.from(allowed).filter((w) => !seen.has(w)).sort();
  const file = path.join(ROOT, 'tgcloud', 'lib', 'words', `${lang}.js`);
  fs.writeFileSync(file, [
    '/*',
    ` * Codeword words (${lang}), generated by scripts/build-words.mjs from ${SOURCES}.`,
    ' * Normalized as in lib/games/codeword.js. ANSWERS: the words that can be picked, most frequent first;',
    ' * GUESSES: the other words accepted as guesses. Space-separated to keep the module small.',
    ' */',
    `export const ANSWERS = '${answers.join(' ')}';`,
    `export const GUESSES = '${extra.join(' ')}';`,
    '',
  ].join('\n'));
  console.log(`${lang}: ${answers.length} answers, ${extra.length} more guesses, ${(fs.statSync(file).size / 1024).toFixed(0)} KB`);
}
